#!/usr/bin/env python3
"""Port the approved Stage 2 explorer logic (PHASE3_STAGE2/WEBSITE/js/app.js) into Stage 3 js/research.js.

The Stage 2 file is only READ. Rendering code is kept unchanged; the Stage 2 router is removed (routing lives
in js/app.js), hash deep links become #research/localities?..., the locality threshold radio is renamed
loc-threshold (the owner wizard has its own threshold control), and three hero labels are reworded so that
the odds-ratio, rating-point and geometric-scale readings are stated next to the numbers.
Run:  python PHASE3_STAGE3/WEBSITE/tools/port_research_explorer.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = ROOT / "PHASE3_STAGE2" / "WEBSITE" / "js" / "app.js"
DST = HERE.parent / "js" / "research.js"

src = SRC.read_text(encoding="utf-8")
start = src.index("  // ======================================================================= router + menu")
end = src.index("  renderOverview();")
body = src[:start] + src[end:]

REPL = [
    ("/* NCR Restaurant Benchmark Explorer: application logic (views, controls, rendering). */",
     "/* NCR Restaurant Intelligence, Research Explorer mode.\n   Generated by tools/port_research_explorer.py from PHASE3_STAGE2/WEBSITE/js/app.js (approved Stage 2 explorer).\n"
     "   Rendering logic is unchanged; routing moved to js/app.js; deep links use #research/localities?...;\n"
     "   the threshold radio is renamed loc-threshold; hero labels state the odds-ratio, rating-point and geometric-scale readings next to the numbers. Do not edit by hand. */"),
    ("(async function () {", "window.NCRResearchReady = (async function () {"),
    ("$$('input[name=\"threshold\"]')", "$$('input[name=\"loc-threshold\"]')"),
    ("location.hash.match(/^#localities\\?(.*)$/)", "location.hash.match(/^#research\\/localities\\?(.*)$/)"),
    ('if (!location.hash.startsWith("#localities")) return;', 'if (!location.hash.startsWith("#research/localities")) return;'),
    ('history.replaceState(null, "", "#localities?" + p.toString());', 'history.replaceState(null, "", "#research/localities?" + p.toString());'),
    ('"<br>Run <code>python build_website_data.py</code>, then serve this folder with <code>python -m http.server 8000</code> and open <code>http://localhost:8000</code>.";',
     '"<br>Serve this folder with <code>python -m http.server 8000</code> and open <code>http://localhost:8000</code>.";'),
    ('hc("visibility", "Visibility", "odds of a published rating (all NCR)", "×" + dv.estimate.toFixed(2), "odds ratio")',
     'hc("visibility", "Visibility", "about ten times the odds of a published rating (all NCR); odds, not probability", "×" + dv.estimate.toFixed(2), "odds ratio")'),
    ('hc("engagement", "Engagement", "geometric mean of (1 + Votes), rated NCR", fmt.signedPct(de.estimate), de.sd_units.toFixed(2) + " SD")',
     'hc("engagement", "Engagement", "higher geometric mean of (1 + Votes), rated NCR; not a % change in raw votes", fmt.signedPct(de.estimate), de.sd_units.toFixed(2) + " SD")'),
    ('hc("quality", "Perceived quality", "rating points, rated NCR", fmt.signed(dq.estimate), dq.sd_units.toFixed(2) + " SD")',
     'hc("quality", "Perceived quality", "rating points higher, rated NCR; not a % change", fmt.signed(dq.estimate), dq.sd_units.toFixed(2) + " SD")'),
    # Stage 3 display correction: performance_extremes.json stores rating SDs at 3 decimals (e.g. 0.155 for 0.1554);
    # Stage 2 re-rounded them to 2 decimals, giving 0.15 where the paper reports 0.16 (double rounding). Show the stored precision.
    ('r.vote_band + " votes (n = " + fmt.int(r.n) + ", SD " + r.sd_rating.toFixed(2) + ")"',
     'r.vote_band + " votes (n = " + fmt.int(r.n) + ", SD " + r.sd_rating.toFixed(3) + ")"'),
]
for a, b in REPL:
    if a not in body:
        raise SystemExit("pattern not found: " + a[:70])
    body = body.replace(a, b, 1)

TAIL = '''
  const VIEWS = { "research": "view-research", "research/cities": "view-cities", "research/localities": "view-localities",
    "research/extremes": "view-extremes", "research/findings": "view-findings", "research/methodology": "view-methodology" };
  function onHashDeepLink() {
    if (!location.hash.startsWith("#research/localities?")) return;
    const before = locState.id + "|" + locState.t;
    readLocHash();
    if (locState.id + "|" + locState.t !== before) {
      $$('input[name="loc-threshold"]').forEach((r) => { r.checked = +r.value === locState.t; });
      locState.q = ""; $("#loc-search").value = "";
      refreshLocControls();
    }
  }
  function onShow(view) {
    const sec = document.getElementById(VIEWS[view]);
    if (sec) C.rerenderVisible(sec);
    if (view === "research/localities") writeLocHash();
  }
  return { onShow, onHashDeepLink, VIEWS };
})();
'''
old_tail = "  route();\n  first = false;\n})();"
if old_tail not in body:
    raise SystemExit("tail not found")
body = body.replace(old_tail, TAIL.lstrip("\n").rstrip("\n").replace("})();", "") + "})();", 1)
DST.write_text(body, encoding="utf-8")
print("wrote", DST, len(body), "bytes")
